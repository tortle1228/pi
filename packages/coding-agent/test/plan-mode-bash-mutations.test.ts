import { describe, expect, it } from "vitest";
import { getMutationReason, toSafeCommand } from "../src/extensions/plan-mode/bash-policy.ts";

describe("Plan mode mutation guard", () => {
	it.each([
		..."rm rmdir mv cp install touch mkdir ln truncate tee chmod chown chgrp sudo"
			.split(" ")
			.map((name) => `${name} target`),
		..."add commit reset restore checkout switch clean merge rebase cherry-pick revert am apply fetch pull push clone init gc prune"
			.split(" ")
			.map((name) => `git ${name}`),
		..."install i ci uninstall remove update publish unpublish".split(" ").map((name) => `npm ${name}`),
		..."apply create delete replace patch edit scale set rollout exec".split(" ").map((name) => `kubectl ${name}`),
		..."apply destroy import".split(" ").map((name) => `terraform ${name}`),
		"'rm' file",
		'"rm" file',
		"/bin/rm file",
		"./rm file",
		"git status && rm file",
		"ls || touch file",
		"cat file | tee out",
		"pwd; mkdir new",
		"rm file;",
		"pwd; rm file;\n",
		"pwd\n\nrm file",
		"git status &&\n git commit -m x",
		"echo x>file",
		"echo x >> 'a file'",
		"echo x 2>errors",
		"echo x 2>>errors",
		"echo x >|file",
		"> file",
		"echo x 2>&1 > file",
		"echo x > /dev/null; rm file",
		"git -C /tmp -c core.foo=bar --git-dir=.git --work-tree=. commit -m x",
		"git -C/tmp -ccore.foo=bar --git-dir=.git --work-tree=. push",
		"git branch new",
		"git branch -d old",
		"git tag v1",
		"git remote add origin url",
		"git stash",
		"git stash push",
		"sed -i 1d file",
		"sed -ni.bak 1p file",
		"sed --in-place=.bak 1d file",
		"find . -delete",
		"find . -fprint out",
		"find . -fprintf out '%p'",
		"find . -fls out",
		"sort -rofile input",
		"sort --output=out input",
		"sort --outp=out input",
		"uniq input out",
		"uniq -f 1 input out",
		"uniq -- - out",
		"uniq -- --input --output",
		"pip install foo",
		"pip3 uninstall foo",
		"uv sync",
		"uv add foo",
		"uv remove foo",
		"uv pip install foo",
		"uv pip uninstall foo",
		"uv pip sync requirements.txt",
		"curl -o out https://example.com",
		"curl -sLO https://example.com",
		"curl -Tfile https://example.com",
		"curl --output=out https://example.com",
		"curl --remote-name https://example.com",
		"curl --upload-file=file https://example.com",
		"curl --data-raw=x https://example.com",
		"curl -sdx https://example.com",
		"curl -F x=y https://example.com",
		"curl --form=x=y https://example.com",
		"curl --json '{}' https://example.com",
		"curl -X POST https://example.com",
		"curl -sXDELETE https://example.com",
		"curl --request=PATCH https://example.com",
		"curl --request PUT https://example.com",
		"terraform apply -refresh-only",
		"kubectl --context=prod delete deployment app",
		"kubectl --context prod -n production delete deployment app",
		"kubectl -nproduction delete deployment app",
		"npm --prefix /tmp/project install foo",
		"npm --prefix=/tmp/project -g install foo",
		"pip --require-virtualenv install foo",
		"pip3 --python /usr/bin/python3 install foo",
		"uv --directory /tmp/project pip install foo",
		"terraform -chdir=infra apply",
		"gh --repo owner/repo pr merge 123",
		"gh -Rowner/repo pr merge 123",
		"curl -A -- -X POST https://example.com",
		"curl -H -- -o out https://example.com",
		"curl -sA-- -X POST https://example.com",
		"find . -name '-delete' -delete",
		"find . -name '--' -delete",
		"sort -to -o out input.txt",
		"kubectl apply --dry-run=client -f manifest.yml",
		...Object.entries({
			pr: "create merge close reopen edit",
			issue: "create close reopen edit",
			release: "create delete edit upload",
			repo: "create delete",
			workflow: "run",
			run: "cancel rerun",
		}).flatMap(([group, verbs]) => verbs.split(" ").map((verb) => `gh ${group} ${verb}`)),
	])("detects %s without executing it", (command) => {
		expect(getMutationReason(command)).toEqual(expect.any(String));
	});

	it.each([
		"git status",
		"git diff",
		"git log -3",
		"git branch -a",
		"git tag --list",
		"git stash list",
		"git remote -v",
		"git -C /tmp -c core.foo=bar status",
		"git remote get-url origin",
		"echo 'rm file'",
		"rg 'a;b > c' file",
		'printf "rm\\n"',
		"cat 'rm file'",
		"echo x > /dev/null",
		"echo x 2>/dev/null",
		"echo x 2>&1",
		"echo x 1>&2",
		"echo x 2>&-",
		"sed -n '1,5p' file",
		"sort -rn file",
		"sort -- -output",
		"find . -name '*.ts'",
		"find . -name '-delete'",
		"find . -iname '-fprint'",
		"find . -printf '-delete'",
		"sort -to input.txt",
		"sort -t o input.txt",
		"sort --field-separator - input.txt",
		"sort -T/output input.txt",
		"kubectl --context delete get pods",
		"npm --prefix install test",
		"terraform -chdir=apply plan",
		"gh --repo pr pr view 1",
		"curl -A -- -X GET https://example.com",
		"curl -- https://example.com/-XPOST",
		"uniq -c file",
		"uniq -f 1 file",
		"uniq --skip-fields 1 file",
		"uniq -- -",
		"uniq -- --file",
		"curl -sL https://example.com",
		"curl -X GET https://example.com",
		"curl -XGET https://example.com",
		"curl -sXHEAD https://example.com",
		"curl --request=OPTIONS https://example.com",
		"curl -H '-data: value' https://example.com",
		"curl -sHContent-Type:text/plain https://example.com",
		"curl --header='X-Test: -d' https://example.com",
		"toString",
		"gh toString view",
		"npm test",
		"npm run check",
		"node script.js",
		"python -c 'print(1)'",
		"bash -c 'rm file'",
		"echo $(rm file)",
		"echo `rm file`",
		"FOO=1 rm file",
		"cat 'unclosed",
		"",
		"terraform plan",
		"kubectl get pods",
		"gh pr view 1",
		"gh run list",
		"uv run script.py",
	])("leaves inspection or unclassified commands to the existing policy: %s", (command) => {
		expect(getMutationReason(command)).toBeUndefined();
	});

	it("does not expand the existing inspection allowlist", () => {
		expect(toSafeCommand("echo x > /dev/null")).toBeUndefined();
		expect(toSafeCommand("ls\npwd")).toBeUndefined();
		expect(toSafeCommand("ls && pwd")).toBeDefined();
	});
});
